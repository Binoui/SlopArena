        {
            ("Light jab", (sbyte)15, 2f, 1.5f, (ushort)20),
            ("Mid launcher", (sbyte)25, 8f, 4f, (ushort)24),
            ("Kill move", (sbyte)20, 18f, 10f, (ushort)24),
        };
        int[] percents = { 0, 50, 150 };
        Model[] models = { Model.Current, Model.OptionA, Model.OptionB };
        string[] modelNames = { "(a) current exp decay", "(b) Option A — constant + linear friction", "(c) Option B — linear decay" };
        char[] modelChars = { 'a', 'b', 'c' };

