// (Flight model feel prototype: trajectory sweep). NOT production code.
// Regenerates docs/research/flight-model-sweep.md from the models below.
//
// Model (a) "current" mirrors src/Shared/Simulation.cs exactly:
//   - launch: ApplyKnockback (:1092) — mag = base + growth*(damage/100),
//     KV = mag*cos(angle) horizontal, mag*sin(angle) vertical
//   - hitstun: clamp(8 + (int)(mag*0.5), 8, 60) capped by StunTicks (:1118)
//   - in-flight: KV *= exp(-1.8*dt) all axes (ProcessHitstun :614, ProcessKnockback :735)
//   - gravity: KnockbackMinGravity = 2.0 m/s² (:49)
// Model (b) "optionA" — Melee-shaped: constant KV through hitstun, full gravity
//   does the vertical work, linear horizontal friction (10 m/s²) after hitstun.
// Model (c) "optionB" — hybrid: linear (constant m/s²) horizontal decay instead
//   of exponential, min gravity kept.
//
// All sweeps launch along +Z from ground height 0, 60 Hz ticks, flight ends on
// landing (y <= 0) or after 600 ticks (10 s cap). Blast zones are stage-specific
// and NOT modeled — this sweep shows trajectory shape + flight metrics only.

using System.Text;

class Program
{
    const float TickDt = 1f / 60f;
    const float ExpLambda = 1.8f;       // Simulation.cs KnockbackDecayRate
    const float MinGravity = 2.0f;      // Simulation.cs KnockbackMinGravity
    const float FullGravity = 36f;      // FightGuy/Kistu stats.Gravity (gravity "doing the work")
    const float LinearDecel = 10f;      // m/s², within research doc's suggested 5-15
    const float DeadZone = 0.015f;      // Simulation.cs VelocityDeadZone
    const int MaxTicks = 600;

    const int PlotW = 72, PlotH = 18;

    enum Model { Current, OptionA, OptionB }

    readonly record struct Launch(float Mag, float KvH, float KvY, int HitstunTicks);

    readonly record struct Flight(float[] H, float[] Y, int HitstunEndIdx, int Ticks, float MaxHeight)
    {
        public float HdistAtHitstunEnd => HitstunEndIdx >= 0 ? H[HitstunEndIdx] : 0f;
        public float TotalHdist => H[^1];
        public float FlightSeconds => (Ticks - 1) * TickDt;
        public bool Capped => Ticks >= MaxTicks;
    }

