        sb.AppendLine("> Prototype artifact for [Flight model feel prototype: trajectory sweep](https://github.com/Binoui/SlopArena/issues/141).");
        sb.AppendLine("> The artifact [*Flight model: Melee-shaped vs hybrid*](https://github.com/Binoui/SlopArena/issues/130) reacts to.");
        sb.AppendLine("> Generated by `dotnet run --project research/flight-sweep` (throwaway code, not production).");
        sb.AppendLine();
        sb.AppendLine("## Method");
        sb.AppendLine();
        sb.AppendLine("- 60 Hz ticks (`TickDt = 1/60`), launch along +Z from ground height 0; flight ends at landing (`Y <= 0`) or the 10 s cap (600 ticks).");
