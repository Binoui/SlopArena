    static Launch LaunchMove(float angleDeg, float baseKB, float growthKB, ushort stunTicks, int damagePct)
    {
        float mag = baseKB + growthKB * (damagePct * 0.01f);          // Simulation.cs:1097
        float rad = angleDeg * MathF.PI / 180f;
        float kvH = mag * MathF.Cos(rad);
        float kvY = mag * MathF.Sin(rad);
        int hitstun = stunTicks > 0 && mag > 0.5f
            ? Math.Min(Math.Clamp(8 + (int)(mag * 0.5f), 8, 60), stunTicks)
            : 0;
        return new Launch(mag, kvH, kvY, hitstun);
    }

    static Flight Simulate(in Launch l, Model model)
    {
        var h = new List<float> { 0f };
        var y = new List<float> { 0f };
        float kvH = l.KvH, kvY = l.KvY;
        int hs = l.HitstunTicks;
        int hsEndIdx = -1;
        int t;
        for (t = 1; t <= MaxTicks; t++)
        {
            bool inHitstun = hs > 0;
            if (inHitstun) hs--;

            switch (model)
            {
                case Model.Current:
                {
                    float decay = MathF.Exp(-ExpLambda * TickDt);
                    kvH *= decay;
                    kvY *= decay;
                    kvY -= MinGravity * TickDt;
                    break;
                }
                case Model.OptionA:
                {
                    // Constant KV through hitstun; full gravity does vertical work.
                    if (!inHitstun)
                    {
                        // Tumble: linear horizontal friction along the launch azimuth.
                        float reduction = MathF.Min(MathF.Abs(kvH), LinearDecel * TickDt);
                        kvH -= MathF.CopySign(reduction, kvH);
                    }
                    kvY -= FullGravity * TickDt;
                    if (MathF.Abs(kvH) < DeadZone) kvH = 0f;
                    break;
                }
                case Model.OptionB:
                {
                    // Linear (constant m/s²) decay per axis — the direct analog of
                    // the current per-axis exponential (each axis decelerates at a
                    // constant rate instead of proportionally), hard stop at v/decel.
                    float hReduction = MathF.Min(MathF.Abs(kvH), LinearDecel * TickDt);
                    kvH -= MathF.CopySign(hReduction, kvH);
                    float yReduction = MathF.Min(MathF.Abs(kvY), LinearDecel * TickDt);
                    kvY -= MathF.CopySign(yReduction, kvY);
                    kvY -= MinGravity * TickDt;
                    if (MathF.Abs(kvH) < DeadZone) kvH = 0f;
                    break;
                }
            }

            float nextH = h[^1] + kvH * TickDt;
            float nextY = y[^1] + kvY * TickDt;
            if (hsEndIdx < 0 && hs == 0) hsEndIdx = h.Count; // index of first post-hitstun sample
            h.Add(nextH);
            y.Add(nextY);
            if (nextY <= 0f) { t++; break; } // landed — flight over
        }
        float maxH = 0f;
        foreach (float v in y) if (v > maxH) maxH = v;
        return new Flight(h.ToArray(), y.ToArray(), hsEndIdx, t, maxH);
    }

    // Option A physics with a parameterized flight gravity (coupling table).
    static Flight SimulateGravity(in Launch l, float gravity)
    {
        var h = new List<float> { 0f };
        var y = new List<float> { 0f };
        float kvH = l.KvH, kvY = l.KvY;
        int hs = l.HitstunTicks;
        int hsEndIdx = -1;
        int t;
        for (t = 1; t <= MaxTicks; t++)
        {
            bool inHitstun = hs > 0;
            if (inHitstun) hs--;
            if (!inHitstun)
            {
                float reduction = MathF.Min(MathF.Abs(kvH), LinearDecel * TickDt);
                kvH -= MathF.CopySign(reduction, kvH);
            }
            kvY -= gravity * TickDt;
            if (MathF.Abs(kvH) < DeadZone) kvH = 0f;

            float nextH = h[^1] + kvH * TickDt;
            float nextY = y[^1] + kvY * TickDt;
            if (hsEndIdx < 0 && hs == 0) hsEndIdx = h.Count;
            h.Add(nextH);
            y.Add(nextY);
            if (nextY <= 0f) { t++; break; }
        }
        float maxH = 0f;
        foreach (float v in y) if (v > maxH) maxH = v;
        return new Flight(h.ToArray(), y.ToArray(), hsEndIdx, t, maxH);
    }

    // ── ASCII plot: all three trajectories overlaid, uppercase marks hitstun end ──
    static string Plot(Flight[] flights)
    {
        float maxH = flights.Max(f => f.MaxHeight);
        float maxDist = flights.Max(f => f.TotalHdist);
        if (maxH <= 0f) maxH = 0.1f;
        if (maxDist <= 0f) maxDist = 1f;
        var grid = new char[PlotH, PlotW];
        for (int r = 0; r < PlotH; r++)
            for (int c = 0; c < PlotW; c++)
                grid[r, c] = '.';

        void Draw(int i, char ch)
        {
            var f = flights[i];
            for (int idx = 0; idx < f.H.Length; idx++)
            {
                int c = (int)Math.Clamp(f.H[idx] / maxDist * (PlotW - 1), 0, PlotW - 1);
                int r = (int)Math.Clamp(f.Y[idx] / maxH * (PlotH - 1), 0, PlotH - 1);
                r = PlotH - 1 - r;
                bool isHsEnd = idx == f.HitstunEndIdx;
                if (isHsEnd)
                    grid[r, c] = char.ToUpperInvariant(ch);
                else if (grid[r, c] == '.')
                    grid[r, c] = ch;
            }
        }

        Draw(0, 'a');
        Draw(1, 'b');
        Draw(2, 'c');

        var lines = new List<string> { $"Y {maxH:F1}m" };
        for (int r = 0; r < PlotH; r++)
        {
            var row = new char[PlotW];
            for (int c = 0; c < PlotW; c++) row[c] = grid[r, c];
            lines.Add(new string(row));
        }
        lines.Add($"0 +{new string('─', PlotW - 2)}+ {maxDist:F1}m  X");
        return string.Join('\n', lines);
    }
